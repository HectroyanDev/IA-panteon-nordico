#!/usr/bin/env node
// Recoge las PRs de GitHub candidatas del modo `nightly` de Tyr con `gh` (solo lectura) y escribe JSON normalizado.
// Uso: node nightly-github.mjs --owner <org> --out <archivo>
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { countChangedLines } from "./classify.mjs";

export const TYR_SIGNATURE = "Generated by Tyr-skill";
export const TOO_LARGE_MARKER = "<!-- tyr:too-large -->";
const SEARCH_FIELDS = "url,repository,number";
const PR_FIELDS = "number,title,isDraft,headRefOid,author,createdAt,url,state,headRefName";
const SLUG = /^[A-Za-z0-9_.-]+$/;

/** Solo lectura: cualquier otra forma lanza antes de ejecutar nada. */
export function assertReadOnly(args) {
  const [a, b] = args;
  const flat = args.join(" ");
  if (args.some((x) => /^(-H|--header)/.test(x))) throw new Error(`cabeceras no permitidas: ${flat}`);
  if (a === "auth" && b === "status") return;
  if (a === "search" && b === "prs") return;
  if (a === "pr" && b === "view") return;
  if (a === "api") {
    if (b === "graphql") throw new Error(`gh api graphql no permitido: ${flat}`);
    if (args.some((x) => /^(-X|--method|-f|-F|--field|--raw-field|--input)/.test(x))) throw new Error(`gh api con método o campos no permitido: ${flat}`);
    return;
  }
  throw new Error(`subcomando de gh no permitido: ${flat}`);
}

function gh(args, run) {
  assertReadOnly(args);
  const r = run("gh", args, { encoding: "utf8", maxBuffer: 128 * 1024 * 1024 });
  if (r.error) return { ok: false, stdout: "", stderr: String(r.error.message) };
  return { ok: r.status === 0, stdout: r.stdout ?? "", stderr: r.stderr ?? "" };
}

const parseJson = (res) => { try { return JSON.parse(res.stdout); } catch { return undefined; } };
const parseLines = (res) => res.stdout.split("\n").filter(Boolean).map((l) => JSON.parse(l));

/** Normaliza una PR a partir de sus datos crudos. Pura. */
export function normalizePr({ view, repo, me, files, reviews, issueComments }) {
  const mine = (x) => x?.user?.login === me;
  // Solo cuentan las firmas del usuario actual: otro autor puede copiar la firma en su texto.
  const signed = (b) => typeof b === "string" && b.includes(TYR_SIGNATURE);
  const tyr = reviews
    .filter((r) => mine(r) && signed(r.body) && r.commit_id)
    .sort((a, b) => String(a.submitted_at).localeCompare(String(b.submitted_at)));
  // Una respuesta en hilo suelta crea una revisión COMMENTED sin cuerpo: no es una revisión manual.
  const manual = reviews.some((r) => mine(r) && r.state !== "PENDING" && !signed(r.body)
    && (r.state === "APPROVED" || r.state === "CHANGES_REQUESTED" || (r.body ?? "").trim() !== ""));
  const notified = [...issueComments, ...reviews].some((c) => mine(c) && typeof c.body === "string" && c.body.includes(TOO_LARGE_MARKER) && signed(c.body));
  return {
    url: view.url,
    platform: "github",
    repo,
    number: view.number,
    author: view.author?.login ?? "",
    title: view.title ?? "",
    branch: view.headRefName ?? "",
    draft: view.isDraft === true,
    changedLines: countChangedLines(files),
    headSha: view.headRefOid,
    lastTyrSha: tyr.length ? tyr[tyr.length - 1].commit_id : null,
    reviewedManually: manual,
    tooLargeNotified: notified,
    createdAt: view.createdAt,
  };
}

/** Devuelve { source, ok, fetchedAt, prs }. `run` permite inyectar un ejecutor en pruebas. */
export function collect({ owner, now = new Date(), run = spawnSync } = {}) {
  const fetchedAt = now.toISOString();
  const fail = (error) => ({ source: "github", ok: false, fetchedAt, error, prs: [] });
  if (!owner || !SLUG.test(owner)) return fail("falta o no es válido --owner");
  if (!gh(["auth", "status"], run).ok) return fail("gh sin sesión");
  const meRes = gh(["api", "user", "-q", ".login"], run);
  const me = meRes.stdout.trim();
  if (!meRes.ok || !me) return fail("no se pudo leer el usuario de gh");

  const found = new Map();
  for (const flag of ["--review-requested=@me", "--reviewed-by=@me"]) {
    const res = gh(["search", "prs", flag, "--state=open", `--owner=${owner}`, "--limit", "100", "--json", SEARCH_FIELDS], run);
    const list = res.ok ? parseJson(res) : undefined;
    if (!Array.isArray(list)) return fail(`gh search prs falló${res.stderr ? `: ${res.stderr.trim().split("\n")[0]}` : ""}`);
    for (const item of list) if (item?.url) found.set(item.url, item);
  }

  const prs = [];
  const errors = [];
  for (const item of found.values()) {
    const repo = item.repository?.nameWithOwner ?? /github\.com\/([^/]+\/[^/]+)\//.exec(item.url)?.[1];
    const [o, name] = (repo ?? "").split("/");
    if (!SLUG.test(o ?? "") || !SLUG.test(name ?? "")) { errors.push(`repositorio desconocido en ${item.url}`); continue; }
    const base = `repos/${o}/${name}`;
    const n = item.number;
    try {
      const view = gh(["pr", "view", item.url, "--json", PR_FIELDS], run);
      const v = view.ok ? parseJson(view) : undefined;
      if (!v) throw new Error("gh pr view falló");
      if (v.state && v.state !== "OPEN") continue;
      if (v.author?.login === me) continue; // las PRs propias no se revisan
      const get = (suffix) => {
        const r = gh(["api", `${base}/${suffix}`, "--paginate", "--jq", ".[]"], run);
        if (!r.ok) throw new Error(`gh api ${suffix} falló`);
        return parseLines(r);
      };
      prs.push(normalizePr({ view: v, repo, me, files: get(`pulls/${n}/files`), reviews: get(`pulls/${n}/reviews`), issueComments: get(`issues/${n}/comments`) }));
    } catch (err) {
      errors.push(`${item.url}: ${err.message}`);
    }
  }
  prs.sort((a, b) => String(a.createdAt).localeCompare(String(b.createdAt)) || a.url.localeCompare(b.url));
  return { source: "github", ok: true, fetchedAt, me, prs, errors };
}

function main(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 2) {
    if (!argv[i].startsWith("--") || argv[i + 1] === undefined) throw new Error(`argumento no válido: ${argv[i]}`);
    args[argv[i].slice(2)] = argv[i + 1];
  }
  if (!args.out) throw new Error("falta --out");
  if (!args.owner) throw new Error("falta --owner");
  const env = collect({ owner: args.owner });
  fs.mkdirSync(path.dirname(path.resolve(args.out)), { recursive: true });
  fs.writeFileSync(args.out, `${JSON.stringify(env, null, 2)}\n`);
  process.stdout.write(`${JSON.stringify({ out: args.out, ok: env.ok, error: env.error ?? null, prs: env.prs.length, errors: env.errors ?? [] })}\n`);
  if (!env.ok) process.exit(1);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  try { main(process.argv.slice(2)); } catch (err) { process.stderr.write(`${err.message}\n`); process.exit(1); }
}
